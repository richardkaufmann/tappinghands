"""Generates Sources/TapHand/EmbeddedArt.swift so the art ships inside the binary
(build.sh copies only the executable into the .app, so SPM resource bundles would be missing).

- Streamline Emojis "index-pointing-up-2" (CC BY 4.0), with its ground-shadow ellipse removed.
- Assets/giraffe.png (cleaned by tools/make_giraffe.py), base64.

Usage: python3 tools/embed_art.py
"""
import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
svg = (ROOT / "docs/hands/streamline-emojis--index-pointing-up-2.svg").read_text().strip()
# Drop the ground shadow: the first <path> with opacity=".15".
svg, n = re.subn(r'<path fill="#45413c" d="[^"]*" opacity="\.15"/>', "", svg, count=1)
assert n == 1, "shadow ellipse not found"
giraffe = base64.b64encode((ROOT / "Assets/giraffe.png").read_bytes()).decode()

out = ROOT / "Sources/TapHand/EmbeddedArt.swift"
out.write_text(f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 Richard Kaufmann
// GENERATED by tools/embed_art.py; do not edit by hand.
import Foundation

enum EmbeddedArt {{
    /// Streamline Emojis "Index pointing up 2" by Streamline (streamlinehq.com), CC BY 4.0
    /// (https://creativecommons.org/licenses/by/4.0/). Modified: ground-shadow ellipse removed.
    static let cartoonHandSVG = ##"{svg}"##

    /// Richard's giraffe photo cut-out, cleaned + flipped + neck faded by tools/make_giraffe.py.
    static let giraffePNG = Data(base64Encoded: "{giraffe}")!
}}
''')
print(f"wrote {out.relative_to(ROOT)} ({len(svg)} B svg, {len(giraffe)} B giraffe b64)")
